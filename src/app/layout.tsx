import type { Metadata, Viewport } from 'next';
import { Inter, Inter_Tight, Instrument_Serif } from 'next/font/google';

import { Analytics } from '@/components/Analytics';
import { SmoothScroll } from '@/components/motion/SmoothScroll';
import { siteConfig } from '@/lib/site';
import { colors } from '@/lib/tokens';

import './globals.css';

/* ---------------------------------------------------------------------------
   Fonts.
   next/font self-hosts and preloads these at build time — no render-blocking
   request to Google, no layout shift (`display: swap` + size-adjust fallbacks).
--------------------------------------------------------------------------- */

/** Body / UI copy. */
const inter = Inter({
  subsets: ['latin'],
  variable: '--font-inter',
  display: 'swap',
});

/** Display headlines — tighter than Inter, gives the editorial punch. */
const interTight = Inter_Tight({
  subsets: ['latin'],
  weight: ['500', '600', '700'],
  variable: '--font-inter-tight',
  display: 'swap',
});

/** The handwritten-feeling italic accent — the slogan, "how it works", etc. */
const instrumentSerif = Instrument_Serif({
  subsets: ['latin'],
  weight: '400',
  style: 'italic',
  variable: '--font-instrument-serif',
  display: 'swap',
});

/* ---------------------------------------------------------------------------
   Metadata
--------------------------------------------------------------------------- */

