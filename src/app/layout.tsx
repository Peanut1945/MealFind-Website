export default function RootLayout({
  children,
}: Readonly<{ children: React.ReactNode }>) {
  return (
    <html
      lang="en-GB"
      className={`${inter.variable} ${interTight.variable} ${instrumentSerif.variable}`}
    >
      <head>
        {/*
          Entrance animations render their `hidden` state into the SSR markup
          (opacity 0, offset by a few px) and rely on JS to animate them in.
          With scripts blocked that would leave the page blank, so force every
          revealed element to its resting state instead. Scoped to
          `[data-reveal]`, which only `<Reveal>` sets.
        */}
        <noscript>
          <style>{`[data-reveal]{opacity:1!important;transform:none!important}`}</style>
        </noscript>
      </head>
      <body className="bg-cream text-ink antialiased">
        {/* Keyboard users land here first. */}
        <a
          href="#main"
          className="sr-only focus:not-sr-only focus:absolute focus:top-3 focus:left-3 focus:z-100 focus:rounded-full focus:bg-forest focus:px-5 focus:py-3 focus:text-sm focus:font-semibold focus:text-cream"
        >
          Skip to main content
        </a>

        <SmoothScroll>{children}</SmoothScroll>

        <script
          type="application/ld+json"
          // Content is a build-time constant, not user input.
          dangerouslySetInnerHTML={{ __html: JSON.stringify(jsonLd) }}
        />

        <Analytics />
      </body>
    </html>
  );
}
